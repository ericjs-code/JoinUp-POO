-- Inspecao somente leitura. Nao aplica migracao nem corrige tabelas existentes.
SELECT VERSION() AS versao_mysql;
SELECT TABLE_NAME, ENGINE FROM information_schema.tables
WHERE TABLE_SCHEMA = 'joinup_poo_ra3' ORDER BY TABLE_NAME;
SELECT TABLE_NAME, COLUMN_NAME, COLUMN_TYPE, IS_NULLABLE, COLUMN_DEFAULT, EXTRA
FROM information_schema.columns WHERE TABLE_SCHEMA = 'joinup_poo_ra3'
ORDER BY TABLE_NAME, ORDINAL_POSITION;
SELECT k.TABLE_NAME, k.COLUMN_NAME, k.REFERENCED_TABLE_NAME, k.REFERENCED_COLUMN_NAME,
       r.DELETE_RULE, r.UPDATE_RULE
FROM information_schema.key_column_usage k
JOIN information_schema.referential_constraints r
  ON r.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA AND r.CONSTRAINT_NAME = k.CONSTRAINT_NAME
WHERE k.CONSTRAINT_SCHEMA = 'joinup_poo_ra3' AND k.REFERENCED_TABLE_NAME IS NOT NULL
ORDER BY k.TABLE_NAME, k.COLUMN_NAME;
SELECT TABLE_NAME, INDEX_NAME, NON_UNIQUE, COLUMN_NAME FROM information_schema.statistics
WHERE TABLE_SCHEMA = 'joinup_poo_ra3' ORDER BY TABLE_NAME, INDEX_NAME, SEQ_IN_INDEX;
SELECT CONSTRAINT_NAME, CHECK_CLAUSE FROM information_schema.check_constraints
WHERE CONSTRAINT_SCHEMA = 'joinup_poo_ra3' ORDER BY CONSTRAINT_NAME;
